// Alias: ids de pestana que comparten dibujo con otro nombre del catalogo.
const ALIASES = { equipo: 'usuarios', metricas: 'estadisticas' };

export function existeIcono(nombre) {
  return Boolean(CATALOGO[ALIASES[nombre] || nombre]);
}

export default function NavIcon({ nombre, className = 'w-5 h-5' }) {
  const rutas = CATALOGO[ALIASES[nombre] || nombre];
  if (!rutas) return null;
  return (
    <svg className={className} fill="none" stroke="currentColor" viewBox="0 0 24 24">
      {rutas.map((d, indice) => (
        <path key={indice} strokeLinecap="round" strokeLinejoin="round" strokeWidth="2" d={d} />
      ))}
    </svg>
  );
}
